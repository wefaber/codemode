import type { TSchema } from '@sinclair/typebox'
import { allows, type Registry } from './registry.ts'

type Json = null | boolean | number | string | Json[] | { [k: string]: Json }
type Schema = { [k: string]: Json }

export type SpecOp = {
  id: string
  scope: string
  summary: string
  input: Schema
  output: Schema
  verbException?: string
}

export type Spec = {
  /** semver of the product API (SPEC R8). */
  version: string
  product: string
  /** Invoked as `await codemode.<product>.<resource>.<verb>(input)`. */
  ops: SpecOp[]
  /** Named schemas, referenced as `{ "$ref": "Item" }`. */
  types: Record<string, Schema>
}

/** Copies a schema to plain JSON and replaces every named schema with a reference. */
function plain(schema: TSchema, named: Set<string>, root = false): Schema {
  const walk = (node: unknown, top: boolean): Json => {
    if (Array.isArray(node)) return node.map((n) => walk(n, false))
    if (node && typeof node === 'object') {
      const obj = node as Record<string, unknown>
      if (!top && typeof obj.$id === 'string' && named.has(obj.$id))
        return { $ref: obj.$id }
      const out: Record<string, Json> = {}
      for (const key of Object.keys(obj)) {
        if (key === '$id' && !top) continue
        out[key] = walk(obj[key], false)
      }
      return out
    }
    return node as Json
  }
  return walk(schema, root) as Schema
}

/** The API as data (what `search` receives). `scopes` limits it to what a token can see. */
export function buildSpec(
  registry: Registry<never>,
  opts: { scopes?: readonly string[] } = {},
): Spec {
  const named = new Set(registry.types.map((s) => String(s.$id)))
  const types: Record<string, Schema> = {}
  for (const type of registry.types) {
    const { $id: _id, ...rest } = plain(type, named, true)
    types[String(type.$id)] = rest
  }
  const scopes = opts.scopes
  const ops = scopes
    ? registry.ops.filter((op) => allows(scopes, op.scope))
    : registry.ops
  return {
    version: registry.version,
    product: registry.product,
    ops: ops.map((op) => ({
      id: op.id,
      scope: op.scope,
      summary: op.summary,
      input: plain(op.input, named),
      output: plain(op.output, named),
      ...(op.verbException ? { verbException: op.verbException } : {}),
    })),
    types,
  }
}

function ts(node: Schema, indent: string): string {
  if (typeof node.$ref === 'string') return node.$ref
  if (Array.isArray(node.anyOf))
    return (node.anyOf as Schema[]).map((n) => ts(n, indent)).join(' | ')
  if ('const' in node) return JSON.stringify(node.const)
  switch (node.type) {
    case 'string':
      return 'string'
    case 'number':
    case 'integer':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array': {
      const inner = ts(node.items as Schema, indent)
      return /[|{]/.test(inner) ? `(${inner})[]` : `${inner}[]`
    }
    case 'object':
      return object(node, indent)
    default:
      return 'unknown'
  }
}

function object(node: Schema, indent: string): string {
  const props = (node.properties ?? {}) as Record<string, Schema>
  const keys = Object.keys(props)
  if (keys.length === 0) return '{}'
  const required = new Set((node.required ?? []) as string[])
  const inner = `${indent}  `
  const lines = keys.map((key) => {
    const doc =
      typeof props[key]!.description === 'string'
        ? `${inner}/** ${props[key]!.description} */\n`
        : ''
    return `${doc}${inner}${key}${required.has(key) ? '' : '?'}: ${ts(props[key]!, inner)}`
  })
  return `{\n${lines.join('\n')}\n${indent}}`
}

/** `client.d.ts`: the named types and the `codemode` object with one function per operation. */
export function renderDts(registry: Registry<never>): string {
  const spec = buildSpec(registry)
  const out: string[] = [
    '// Generated by `wcm gen` from the registry. Do not edit by hand.',
    '',
  ]
  for (const [name, schema] of Object.entries(spec.types)) {
    if (typeof schema.description === 'string')
      out.push(`/** ${schema.description} */`)
    out.push(`interface ${name} ${object(schema, '')}`, '')
  }
  const groups = new Map<string, SpecOp[]>()
  for (const op of spec.ops) {
    const resource = op.id.split('.')[1]!
    groups.set(resource, [...(groups.get(resource) ?? []), op])
  }
  out.push('declare const codemode: {', `  ${spec.product}: {`)
  for (const [resource, ops] of groups) {
    out.push(`    ${resource}: {`)
    for (const op of ops) {
      const verb = op.id.split('.')[2]!
      const input = ts(op.input, '      ')
      const arg = input === '{}' ? '' : `input: ${input}`
      out.push(
        `      /** ${op.summary} [${op.scope}] */`,
        `      ${verb}(${arg}): Promise<${ts(op.output, '      ')}>`,
      )
    }
    out.push('    }')
  }
  out.push('  }', '}', '')
  return out.join('\n')
}
